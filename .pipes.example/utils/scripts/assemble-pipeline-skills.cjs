#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');

const PIPE_ROOT = path.resolve(__dirname, '..', '..');
const CANONICAL_WORKFLOW_CONTRACT = '.pipes/ai-instructions/core-workflows.md';
const WORKSPACE_ROOT = path.dirname(PIPE_ROOT);
const PIPELINE_DIR = path.join(PIPE_ROOT, 'utils/pipelines');
const CANONICAL_ROOT = '.pipes';
const BT = String.fromCharCode(96);
const MARKER_START = '<!-- pipes-pipeline-skill:start -->';
const MARKER_END = '<!-- pipes-pipeline-skill:end -->';
const TARGET_MAP = {
  agents: { id: 'agents', root: '.agents/skills' },
  claude: { id: 'claude', root: '.claude/skills' },
};
const DEFAULT_TARGETS = ['agents', 'claude'];

function parseArgs(argv) {
  const flags = { targets: null, json: false, list: false };
  for (let index = 2; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--json') flags.json = true;
    else if (arg === '--list') flags.list = true;
    else if (arg === '--targets' || arg === '--target') {
      flags.targets = argv[index + 1] || '';
      index += 1;
    } else if (arg.startsWith('--targets=')) flags.targets = arg.slice(10);
    else if (arg.startsWith('--target=')) flags.targets = arg.slice(9);
  }
  return flags;
}

function resolveTargets(value) {
  const ids = value
    ? value.split(',').map((item) => item.trim()).filter(Boolean)
    : DEFAULT_TARGETS;
  const invalid = ids.find((id) => !TARGET_MAP[id]);
  if (invalid) throw new Error('Invalid target "' + invalid + '".');
  return ids.map((id) => TARGET_MAP[id]);
}

function scalar(content, key) {
  const match = String(content).match(new RegExp('^' + key + ':\\s*(.+)$', 'm'));
  return match ? match[1].trim().replace(/^["']|["']$/g, '') : '';
}

function discoverPipelines(dir = PIPELINE_DIR) {
  if (!fs.existsSync(dir)) throw new Error('Pipeline directory is missing.');
  return fs.readdirSync(dir)
    .filter((name) => /^pipeline-.+\.md$/.test(name))
    .sort()
    .map((filename) => {
      const content = fs.readFileSync(path.join(dir, filename), 'utf8');
      const id = filename.slice(0, -3);
      const slug = id.replace(/^pipeline-/, '');
      return {
        filename,
        id,
        slug,
        title: scalar(content, 'title') || id,
        description: scalar(content, 'description'),
        skillName: 'pipes.' + slug,
        canonicalPath: CANONICAL_ROOT + '/utils/pipelines/' + filename,
      };
    });
}

function escapeYaml(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

const WORKFLOW_CONTRACT_PATH = 'ai-instructions/core-workflows.md';
const WORKFLOW_CONTRACT_STEP = 'Read ' + BT + CANONICAL_WORKFLOW_CONTRACT + BT + ' first; it is part of the Pipes core contract.';

function hasWorkflowContract(root = PIPE_ROOT) {
  return fs.existsSync(path.join(root, WORKFLOW_CONTRACT_PATH));
}

function numberedSteps(steps) {
  return steps.map((step, index) => String(index + 1) + '. ' + step);
}

function renderSkill(pipeline) {
  return [
    '---',
    'name: ' + pipeline.skillName,
    'description: "Run the local Pipes pipeline ' + escapeYaml(pipeline.title)
      + '. Use when the user asks for ' + pipeline.id + ' or the workflow it describes."',
    '---',
    '',
    MARKER_START,
    'Generated by Pipes. Source: ' + pipeline.canonicalPath,
    MARKER_END,
    '',
    '# ' + pipeline.title,
    '',
    ...numberedSteps([
      ...(hasWorkflowContract() ? [WORKFLOW_CONTRACT_STEP] : []),
      'Read ' + BT + pipeline.canonicalPath + BT + ' before acting.',
      'Use the user\'s current request and relevant project context as input.',
      'Preserve the pipeline\'s phase order and explicit approval gates.',
      'When a loop invokes it, follow ' + BT + '## Loop Use' + BT
        + ' and the active mission\'s scope.',
      'Resolve each fragment ID by exact filename to exactly one file under ' + BT
        + '.pipes/utils/fragments/' + BT
        + '; never infer its type directory. Read only the fragments and rules needed for the current phase.',
      'After a pause, inspect actual outputs and continue from the first incomplete phase.',
      'Stop for a declared gate, blocker, protected action, or missing authority; otherwise continue through the workflow.',
      'Return concise outputs, changed paths, validation evidence, and remaining risk.',
    ]),
    '',
  ].join('\n');
}

function writeSkill(target, pipeline) {
  const rel = path.join(target.root, pipeline.skillName, 'SKILL.md');
  const full = path.join(WORKSPACE_ROOT, rel);
  if (fs.existsSync(full) && !fs.readFileSync(full, 'utf8').includes(MARKER_START)) {
    return {
      status: 'success',
      action: 'skipped',
      target: target.id,
      path: rel,
      skillName: pipeline.skillName,
    };
  }
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, renderSkill(pipeline), 'utf8');
  return {
    status: 'success',
    action: 'written',
    target: target.id,
    path: rel,
    skillName: pipeline.skillName,
  };
}

function removeStale(target, expected) {
  const root = path.join(WORKSPACE_ROOT, target.root);
  if (!fs.existsSync(root)) return [];
  const results = [];
  const directories = fs.readdirSync(root, { withFileTypes: true })
    .filter((item) => item.isDirectory());
  for (const entry of directories) {
    const file = path.join(root, entry.name, 'SKILL.md');
    if (!fs.existsSync(file) || expected.has(entry.name)) continue;
    if (!fs.readFileSync(file, 'utf8').includes(MARKER_START)) continue;
    fs.rmSync(path.dirname(file), { recursive: true, force: true });
    results.push({
      status: 'success',
      action: 'removed',
      target: target.id,
      skillName: entry.name,
      path: path.relative(WORKSPACE_ROOT, file),
    });
  }
  return results;
}

function generatePipelineSkills({ targets = null } = {}) {
  const pipelines = discoverPipelines();
  const expected = new Set(pipelines.map((item) => item.skillName));
  const results = [];
  for (const target of resolveTargets(targets)) {
    pipelines.forEach((pipeline) => results.push(writeSkill(target, pipeline)));
    results.push(...removeStale(target, expected));
  }
  return { ok: true, results, sources: { pipelines: pipelines.length } };
}

function runCli() {
  const flags = parseArgs(process.argv);
  try {
    if (flags.list) {
      console.log(discoverPipelines().map((item) => item.id).join('\n'));
      return;
    }
    const result = generatePipelineSkills({ targets: flags.targets });
    if (flags.json) console.log(JSON.stringify(result));
    else {
      result.results.forEach((item) => {
        console.log('✓ ' + item.target + ' ' + item.skillName + ' ' + item.action);
      });
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

if (require.main === module) runCli();

module.exports = {
  hasWorkflowContract,
  discoverPipelines,
  generatePipelineSkills,
  parseArgs,
  removeStale,
  renderSkill,
  resolveTargets,
  TARGET_MAP,
};
