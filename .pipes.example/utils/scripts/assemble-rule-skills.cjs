#!/usr/bin/env node
// Generates one triggered skill per rule that declares `skill: true`. The rule Markdown under
// .pipes/utils/rules/ stays canonical; each skill only points to it and never copies its text.
// Targets: .claude/skills and .agents/skills (both read SKILL.md). Other targets read the rule.
const fs = require('node:fs');
const path = require('node:path');

const PIPE_ROOT = path.resolve(__dirname, '..', '..');
const WORKSPACE_ROOT = path.dirname(PIPE_ROOT);
const BT = String.fromCharCode(96);
const MARKER_START = '<!-- pipes-rule-skill:start -->';
const MARKER_END = '<!-- pipes-rule-skill:end -->';
const TARGETS = {
  agents: { id: 'agents', root: '.agents/skills' },
  claude: { id: 'claude', root: '.claude/skills' },
};

function parseArgs(argv) {
  const options = { check: false, root: WORKSPACE_ROOT, pipeRoot: PIPE_ROOT };
  for (let index = 2; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--check') options.check = true;
    else if (arg === '--root') { options.root = path.resolve(argv[index + 1] || ''); index += 1; }
    else throw new Error('Unknown argument: ' + arg);
  }
  return options;
}

function frontmatter(content) {
  const block = String(content).match(/^---\r?\n([\s\S]*?)\r?\n---/)?.[1] || '';
  const meta = {};
  for (const line of block.split(/\r?\n/)) {
    const item = line.match(/^([a-z][a-z0-9_]*):\s*(.*)$/i);
    if (item) meta[item[1]] = item[2].trim().replace(/^["']|["']$/g, '');
  }
  return meta;
}

function discoverRuleSkills(pipeRoot = PIPE_ROOT) {
  const dir = path.join(pipeRoot, 'utils/rules');
  return fs.readdirSync(dir)
    .filter((name) => /^rule-.+\.md$/.test(name))
    .sort()
    .map((name) => ({ name, meta: frontmatter(fs.readFileSync(path.join(dir, name), 'utf8')) }))
    .filter(({ meta }) => meta.skill === 'true')
    .map(({ name, meta }) => {
      const id = name.slice(0, -3);
      if (!meta.skill_description) throw new Error(name + ' declares skill: true without skill_description.');
      return {
        id,
        title: meta.title || id,
        description: meta.skill_description,
        skillName: 'pipes.policy-' + id.replace(/^rule-/, ''),
        canonicalPath: '.pipes/utils/rules/' + name,
      };
    });
}

function renderSkill(rule) {
  return [
    '---',
    'name: ' + rule.skillName,
    'description: ' + JSON.stringify(rule.description),
    '---',
    '',
    MARKER_START,
    'Generated by Pipes. Source: ' + rule.canonicalPath,
    MARKER_END,
    '',
    '# ' + rule.title,
    '',
    '1. Read ' + BT + rule.canonicalPath + BT + ' completely before acting. It is the policy; this skill only points to it.',
    '2. Apply every check in its ' + BT + '## Checks' + BT + ' section to the work in front of you: a spec, plan, diff, or review.',
    '3. When the target service repository states a stricter or more specific rule, follow both; report a contradiction instead of choosing silently.',
    '4. Cite each violation with the file path and line, the rule check it breaks, and a concrete correction.',
    '',
  ].join('\n');
}

function generate(options = {}) {
  const root = options.root || WORKSPACE_ROOT;
  const rules = discoverRuleSkills(options.pipeRoot || PIPE_ROOT);
  const results = [];
  for (const target of Object.values(TARGETS)) {
    const base = path.join(root, target.root);
    const wanted = new Set(rules.map((rule) => rule.skillName));
    for (const rule of rules) {
      const file = path.join(base, rule.skillName, 'SKILL.md');
      const next = renderSkill(rule);
      const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
      if (current !== null && !current.includes(MARKER_START)) throw new Error('Refusing to overwrite unmanaged skill ' + path.relative(root, file));
      const action = current === next ? 'unchanged' : current === null ? 'created' : 'updated';
      if (action !== 'unchanged' && !options.check) {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, next, 'utf8');
      }
      results.push({ target: target.id, skillName: rule.skillName, action });
    }
    if (fs.existsSync(base)) {
      for (const entry of fs.readdirSync(base, { withFileTypes: true }).filter((item) => item.isDirectory())) {
        const file = path.join(base, entry.name, 'SKILL.md');
        if (wanted.has(entry.name) || !fs.existsSync(file) || !fs.readFileSync(file, 'utf8').includes(MARKER_START)) continue;
        if (!options.check) fs.rmSync(path.dirname(file), { recursive: true, force: true });
        results.push({ target: target.id, skillName: entry.name, action: 'removed' });
      }
    }
  }
  return { results, stale: results.some((item) => item.action !== 'unchanged') };
}

function main() {
  const options = parseArgs(process.argv);
  const { results, stale } = generate(options);
  for (const item of results) console.log((options.check ? '? ' : '✓ ') + item.target + ' ' + item.skillName + ' ' + item.action);
  if (options.check && stale) {
    process.stderr.write('Generated policy skills are stale; run assemble-rule-skills.cjs.\n');
    process.exitCode = 1;
  }
}

if (require.main === module) {
  try { main(); }
  catch (error) { process.stderr.write(error.message + '\n'); process.exitCode = 1; }
}

module.exports = { discoverRuleSkills, generate, parseArgs, renderSkill, MARKER_START };
